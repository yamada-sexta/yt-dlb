export interface CookieInit {
  name: string;
  value: string;
  domain: string;
  path?: string;
  secure?: boolean;
  expires?: number | null;
  httpOnly?: boolean;
  discard?: boolean;
}

export class Cookie {
  name: string;
  value: string;
  domain: string;
  path: string;
  secure: boolean;
  expires: number | null;
  httpOnly: boolean;
  discard: boolean;

  constructor(init: CookieInit) {
    this.name = init.name;
    this.value = init.value;
    this.domain = init.domain;
    this.path = init.path ?? "/";
    this.secure = Boolean(init.secure);
    this.expires = init.expires ?? null;
    this.httpOnly = Boolean(init.httpOnly);
    this.discard = Boolean(init.discard);
  }

  isExpired(now = Date.now() / 1000): boolean {
    return this.expires !== null && this.expires <= now;
  }
}

export class YoutubeDLCookieJar implements Iterable<Cookie> {
  static readonly HTTPONLY_PREFIX = "#HttpOnly_";
  static readonly ENTRY_LEN = 7;
  static readonly HEADER =
    "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n";

  readonly #cookies: Cookie[] = [];

  constructor(public filename: string | null = null) {}

  [Symbol.iterator](): Iterator<Cookie> {
    return this.#cookies[Symbol.iterator]();
  }

  get length(): number {
    return this.#cookies.length;
  }

  setCookie(cookie: Cookie): void {
    const index = this.#cookies.findIndex(
      (candidate) =>
        candidate.domain === cookie.domain &&
        candidate.path === cookie.path &&
        candidate.name === cookie.name,
    );
    if (index !== -1) {
      this.#cookies.splice(index, 1);
    }
    this.#cookies.push(cookie);
  }

  clear(domain?: string, path?: string, name?: string): void {
    if (!domain) {
      this.#cookies.splice(0);
      return;
    }
    for (let index = this.#cookies.length - 1; index >= 0; index -= 1) {
      const cookie = this.#cookies[index];
      if (!cookie) {
        continue;
      }
      if (
        cookie.domain === domain &&
        (path === undefined || cookie.path === path) &&
        (name === undefined || cookie.name === name)
      ) {
        this.#cookies.splice(index, 1);
      }
    }
  }

  async save(
    filename = this.filename,
    ignoreDiscard = true,
    ignoreExpires = true,
  ): Promise<void> {
    if (!filename) {
      throw new Error("missing filename");
    }
    const now = Date.now() / 1000;
    const lines = [YoutubeDLCookieJar.HEADER];
    for (const cookie of this.#cookies) {
      if (
        (!ignoreDiscard && cookie.discard) ||
        (!ignoreExpires && cookie.isExpired(now))
      ) {
        continue;
      }
      let name = cookie.name;
      let value = cookie.value;
      if (value === undefined || value === null) {
        value = name;
        name = "";
      }
      const domain = `${cookie.httpOnly ? YoutubeDLCookieJar.HTTPONLY_PREFIX : ""}${cookie.domain}`;
      lines.push(
        [
          domain,
          trueOrFalse(cookie.domain.startsWith(".")),
          cookie.path,
          trueOrFalse(cookie.secure),
          cookie.expires ?? 0,
          name,
          value,
        ].join("\t"),
        "\n",
      );
    }
    await Bun.write(filename, lines.join(""));
  }

  async load(
    filename = this.filename,
    _ignoreDiscard = true,
    _ignoreExpires = true,
  ): Promise<void> {
    if (!filename) {
      throw new Error("missing filename");
    }
    const text = await Bun.file(filename).text();
    for (const rawLine of text.split(/\r?\n/)) {
      const line = rawLine.trimEnd();
      if (
        !line ||
        (line.startsWith("#") &&
          !line.startsWith(YoutubeDLCookieJar.HTTPONLY_PREFIX))
      ) {
        continue;
      }
      try {
        this.setCookie(parseNetscapeCookieLine(line));
      } catch (error) {
        if (/^[[{"]/.test(line.trim())) {
          throw new Error(
            "Cookies file must be Netscape formatted, not JSON. See https://github.com/yt-dlp/yt-dlp/wiki/FAQ#how-do-i-pass-cookies-to-yt-dlp",
          );
        }
        console.warn(
          `WARNING: skipping cookie file entry due to ${error}: ${JSON.stringify(line)}`,
        );
      }
    }
  }

  getCookieHeader(url: string): string | undefined {
    const parsed = new URL(url);
    const now = Date.now() / 1000;
    const pairs = this.#cookies
      .filter((cookie) => cookieMatchesUrl(cookie, parsed, now))
      .map((cookie) => `${cookie.name}=${cookie.value}`);
    return pairs.length ? pairs.join("; ") : undefined;
  }

  getCookiesForUrl(url: string): Cookie[] {
    const parsed = new URL(url);
    const now = Date.now() / 1000;
    return this.#cookies.filter((cookie) =>
      cookieMatchesUrl(cookie, parsed, now),
    );
  }
}

export async function loadCookies(
  cookieFile: string | null | undefined,
  browserSpecification:
    | readonly [string, string?, string?, string?]
    | null
    | undefined,
  _ydl?: unknown,
): Promise<YoutubeDLCookieJar> {
  try {
    const jars: YoutubeDLCookieJar[] = [];
    if (browserSpecification) {
      // Logic change: Sweet Cookie requires a target URL for origin filtering. Browser cookies are
      // now loaded lazily per request URL by YoutubeDL instead of eagerly at startup.
      parseBrowserSpecification(...browserSpecification);
    }
    if (cookieFile) {
      const jar = new YoutubeDLCookieJar(expandPath(cookieFile));
      if (await fileExists(jar.filename)) {
        await jar.load();
      }
      jars.push(jar);
    }
    return mergeCookieJars(jars);
  } catch (error) {
    throw new CookieLoadError(
      `failed to load cookies: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
}

export async function extractCookiesFromBrowserForUrl(
  browserSpecification: readonly [string, string?, string?, string?],
  url: string,
  logger: CookieLogger = new YDLLogger(),
): Promise<YoutubeDLCookieJar> {
  const [browserName, profile, keyring, container] = parseBrowserSpecification(
    ...browserSpecification,
  );
  if (container && container !== "none") {
    logger.warning(
      "Firefox container selection is not supported by Sweet Cookie; falling back to ytdlb's Firefox cookie reader",
      { onlyOnce: true },
    );
    return filterCookieJarForUrl(
      await extractCookiesFromBrowser(browserName, profile, logger, {
        keyring,
        container,
      }),
      url,
    );
  }

  const options = sweetCookieOptions(browserName, profile, url);
  if (!options) {
    logger.warning(
      `Sweet Cookie does not directly support ${browserName}; falling back to ytdlb's browser cookie reader`,
      { onlyOnce: true },
    );
    return filterCookieJarForUrl(
      await extractCookiesFromBrowser(browserName, profile, logger, {
        keyring,
        container,
      }),
      url,
    );
  }

  try {
    const result = await getCookies(options);
    for (const warning of result.warnings) {
      logger.warning(warning, { onlyOnce: true });
    }
    const jar = new YoutubeDLCookieJar();
    for (const cookie of result.cookies) {
      jar.setCookie(sweetCookieToYtdlbCookie(cookie, url));
    }
    logger.info(
      `Extracted ${jar.length} cookies from ${browserName} for ${new URL(url).origin}`,
    );
    return jar;
  } catch (error) {
    logger.warning(
      `Sweet Cookie failed for ${browserName}: ${error instanceof Error ? error.message : String(error)}`,
      { onlyOnce: true },
    );
    return filterCookieJarForUrl(
      await extractCookiesFromBrowser(browserName, profile, logger, {
        keyring,
        container,
      }),
      url,
    );
  }
}

export async function extractCookiesFromBrowser(
  browserName: string,
  profile?: string | null,
  logger: CookieLogger = new YDLLogger(),
  options: { keyring?: string | null; container?: string | null } = {},
): Promise<YoutubeDLCookieJar> {
  if (browserName === "firefox") {
    return await extractFirefoxCookies(
      profile ?? null,
      options.container ?? null,
      logger,
    );
  }
  if (browserName === "safari") {
    return await extractSafariCookies(profile ?? null, logger);
  }
  if (CHROMIUM_BASED_BROWSERS.has(browserName)) {
    return await extractChromeCookies(
      browserName,
      profile ?? null,
      options.keyring ?? null,
      logger,
    );
  }
  throw new Error(`unknown browser: ${browserName}`);
}

export async function extractFirefoxCookies(
  profile: string | null,
  container: string | null,
  logger: CookieLogger,
): Promise<YoutubeDLCookieJar> {
  logger.info("Extracting cookies from firefox");
  const roots =
    profile === null
      ? firefoxBrowserDirs()
      : isPath(profile)
        ? [profile]
        : firefoxBrowserDirs().map((path) => join(path, profile));
  const cookieDatabasePath = await newest(await firefoxCookieDbs(roots));
  if (!cookieDatabasePath) {
    throw new Error(
      `could not find firefox cookies database in ${roots.map((root) => JSON.stringify(root)).join(", ")}`,
    );
  }

  let containerId: number | null = null;
  if (container !== null && container !== "none") {
    const containersPath = join(dirname(cookieDatabasePath), "containers.json");
    const identities =
      JSON.parse(await Bun.file(containersPath).text()).identities ?? [];
    containerId = identities.find(
      (identity: Record<string, unknown>) =>
        identity.name === container ||
        /^userContext(.+)\.label$/.exec(String(identity.l10nID ?? ""))?.[1] ===
          container,
    )?.userContextId;
    if (typeof containerId !== "number") {
      throw new Error(
        `could not find firefox container "${container}" in containers.json`,
      );
    }
  }

  const tmp = await mkdtemp(join(tmpdir(), "yt_dlp"));
  try {
    const dbPath = await openDatabaseCopy(cookieDatabasePath, tmp);
    const db = new Database(dbPath, { readonly: true });
    try {
      const versionRow = db.query("PRAGMA user_version").get() as Record<
        string,
        number
      > | null;
      const schemaVersion = Object.values(versionRow ?? {})[0] ?? 0;
      if (schemaVersion > 17) {
        logger.warning(
          `Possibly unsupported firefox cookies database version: ${schemaVersion}`,
        );
      }
      const jar = new YoutubeDLCookieJar();
      const rows = queryFirefoxRows(db, container, containerId);
      for (const row of rows) {
        const expiry =
          schemaVersion >= 16 && row.expiry != null
            ? Math.trunc(row.expiry / 1000)
            : row.expiry;
        jar.setCookie(
          new Cookie({
            name: row.name,
            value: row.value,
            domain: row.host,
            path: row.path,
            secure: Boolean(row.isSecure),
            expires: expiry ?? null,
            discard: false,
          }),
        );
      }
      logger.info(`Extracted ${jar.length} cookies from firefox`);
      return jar;
    } finally {
      db.close();
    }
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

export async function extractChromeCookies(
  browserName: string,
  profile: string | null,
  keyring: string | null,
  logger: CookieLogger,
): Promise<YoutubeDLCookieJar> {
  logger.info(`Extracting cookies from ${browserName}`);
  const config = getChromiumBasedBrowserSettings(browserName);
  const searchRoot =
    profile === null
      ? config.browserDir
      : isPath(profile)
        ? profile
        : config.supportsProfiles
          ? join(config.browserDir, profile)
          : config.browserDir;
  const cookieDatabasePath = await newest(
    await findFiles(searchRoot, "Cookies"),
  );
  if (!cookieDatabasePath) {
    throw new Error(
      `could not find ${browserName} cookies database in "${searchRoot}"`,
    );
  }

  const tmp = await mkdtemp(join(tmpdir(), "yt_dlp"));
  try {
    const dbPath = await openDatabaseCopy(cookieDatabasePath, tmp);
    const db = new Database(dbPath, { readonly: true });
    try {
      const columns = getColumnNames(db, "cookies");
      const secureColumn = columns.includes("is_secure")
        ? "is_secure"
        : "secure";
      const rows = db
        .query(
          `SELECT host_key, name, value, encrypted_value, path, expires_utc, ${secureColumn} as is_secure FROM cookies`,
        )
        .all() as ChromeCookieRow[];
      const metaRow = db
        .query('SELECT value FROM meta WHERE key = "version"')
        .get() as { value?: string } | null;
      const decryptor = getCookieDecryptor(
        config.browserDir,
        config.keyringName,
        logger,
        { keyring, metaVersion: Number(metaRow?.value ?? 0) },
      );
      const jar = new YoutubeDLCookieJar();
      let failed = 0;
      for (const row of rows) {
        const [_, cookie] = processChromeCookie(decryptor, row);
        if (!cookie) {
          failed += 1;
          continue;
        }
        jar.setCookie(cookie);
      }
      logger.info(
        `Extracted ${jar.length} cookies from ${browserName}${failed ? ` (${failed} could not be decrypted)` : ""}`,
      );
      return jar;
    } finally {
      db.close();
    }
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

export async function extractSafariCookies(
  profile: string | null,
  logger: CookieLogger,
): Promise<YoutubeDLCookieJar> {
  if (process.platform !== "darwin") {
    throw new Error(`unsupported platform: ${process.platform}`);
  }
  const cookiesPath = profile
    ? expandPath(profile)
    : await newest([
        expandPath("~/Library/Cookies/Cookies.binarycookies"),
        expandPath(
          "~/Library/Containers/com.apple.Safari/Data/Library/Cookies/Cookies.binarycookies",
        ),
      ]);
  if (!cookiesPath || !(await fileExists(cookiesPath))) {
    throw new Error("could not find safari cookies database");
  }
  const jar = parseSafariCookies(
    new Uint8Array(await Bun.file(cookiesPath).arrayBuffer()),
    undefined,
    logger,
  );
  logger.info(`Extracted ${jar.length} cookies from safari`);
  return jar;
}

export class ChromeCookieDecryptor {
  readonly cookieCounts: Record<string, number> = {};
  decrypt(_encryptedValue: Uint8Array): string | null {
    throw new Error("Must be implemented by subclasses");
  }
}

export function getCookieDecryptor(
  browserRoot: string,
  browserKeyringName: string,
  logger: CookieLogger,
  options: { keyring?: string | null; metaVersion?: number | null } = {},
): ChromeCookieDecryptor {
  if (process.platform === "darwin") {
    return new MacChromeCookieDecryptor(
      browserKeyringName,
      logger,
      options.metaVersion ?? 0,
    );
  }
  if (process.platform === "win32") {
    return new WindowsChromeCookieDecryptor(
      browserRoot,
      logger,
      options.metaVersion ?? 0,
    );
  }
  return new LinuxChromeCookieDecryptor(
    browserKeyringName,
    logger,
    options.keyring ?? null,
    options.metaVersion ?? 0,
  );
}

export class LinuxChromeCookieDecryptor extends ChromeCookieDecryptor {
  readonly #v10Key = deriveLinuxKey(Buffer.from("peanuts"));
  readonly #emptyKey = deriveLinuxKey(Buffer.alloc(0));
  readonly #metaVersion: number;

  override readonly cookieCounts = { v10: 0, v11: 0, other: 0 };

  constructor(
    readonly browserKeyringName: string,
    readonly logger: CookieLogger,
    readonly keyring: string | null,
    metaVersion: number,
  ) {
    super();
    this.#metaVersion = metaVersion;
  }

  static deriveKey(password: Uint8Array): Buffer {
    return deriveLinuxKey(password);
  }

  override decrypt(encryptedValue: Uint8Array): string | null {
    const version = Buffer.from(encryptedValue.subarray(0, 3)).toString();
    const ciphertext = encryptedValue.subarray(3);
    if (version === "v10") {
      this.cookieCounts.v10 += 1;
      return decryptAesCbcMulti(
        ciphertext,
        [this.#v10Key, this.#emptyKey],
        this.logger,
        undefined,
        this.#metaVersion >= 24,
      );
    }
    if (version === "v11") {
      this.cookieCounts.v11 += 1;
      const key = this.getV11Key();
      return key
        ? decryptAesCbcMulti(
            ciphertext,
            [key, this.#emptyKey],
            this.logger,
            undefined,
            this.#metaVersion >= 24,
          )
        : null;
    }
    this.cookieCounts.other += 1;
    this.logger.warning(`unknown cookie version: "${version}"`, {
      onlyOnce: true,
    });
    return null;
  }

  private getV11Key(): Buffer | null {
    const password = getLinuxKeyringPassword(
      this.browserKeyringName,
      this.keyring,
      this.logger,
    );
    return password ? deriveLinuxKey(password) : null;
  }
}

export class MacChromeCookieDecryptor extends ChromeCookieDecryptor {
  readonly #key: Buffer | null;
  readonly #metaVersion: number;
  override readonly cookieCounts = { v10: 0, other: 0 };

  constructor(
    browserKeyringName: string,
    readonly logger: CookieLogger,
    metaVersion: number,
  ) {
    super();
    const password = getMacKeyringPassword(browserKeyringName, logger);
    this.#key = password ? MacChromeCookieDecryptor.deriveKey(password) : null;
    this.#metaVersion = metaVersion;
  }

  static deriveKey(password: Uint8Array): Buffer {
    return pbkdf2Sha1(password, Buffer.from("saltysalt"), 1003, 16);
  }

  override decrypt(encryptedValue: Uint8Array): string | null {
    const version = Buffer.from(encryptedValue.subarray(0, 3)).toString();
    const ciphertext = encryptedValue.subarray(3);
    if (version === "v10") {
      this.cookieCounts.v10 += 1;
      return this.#key
        ? decryptAesCbcMulti(
            ciphertext,
            [this.#key],
            this.logger,
            undefined,
            this.#metaVersion >= 24,
          )
        : null;
    }
    this.cookieCounts.other += 1;
    return Buffer.from(encryptedValue).toString();
  }
}

export class WindowsChromeCookieDecryptor extends ChromeCookieDecryptor {
  readonly #key: Buffer | null;
  readonly #metaVersion: number;
  override readonly cookieCounts = { v10: 0, other: 0 };

  constructor(
    browserRoot: string,
    readonly logger: CookieLogger,
    metaVersion: number,
  ) {
    super();
    this.#key = getWindowsV10Key(browserRoot, logger);
    this.#metaVersion = metaVersion;
  }

  override decrypt(encryptedValue: Uint8Array): string | null {
    const version = Buffer.from(encryptedValue.subarray(0, 3)).toString();
    const ciphertext = encryptedValue.subarray(3);
    if (version === "v10") {
      this.cookieCounts.v10 += 1;
      if (!this.#key) {
        this.logger.warning("cannot decrypt v10 cookies: no key found", {
          onlyOnce: true,
        });
        return null;
      }
      const nonceLength = 12;
      const tagLength = 16;
      return decryptAesGcm(
        ciphertext.subarray(nonceLength, ciphertext.length - tagLength),
        this.#key,
        ciphertext.subarray(0, nonceLength),
        ciphertext.subarray(ciphertext.length - tagLength),
        this.logger,
        this.#metaVersion >= 24,
      );
    }
    this.cookieCounts.other += 1;
    return decryptWindowsDpapi(encryptedValue, this.logger)?.toString() ?? null;
  }
}

export function pbkdf2Sha1(
  password: Uint8Array,
  salt: Uint8Array,
  iterations: number,
  keyLength: number,
): Buffer {
  return pbkdf2Sync(password, salt, iterations, keyLength, "sha1");
}

export function decryptAesCbcMulti(
  ciphertext: Uint8Array,
  keys: readonly Uint8Array[],
  logger: CookieLogger,
  initializationVector = Buffer.alloc(16, " "),
  hashPrefix = false,
): string | null {
  for (const key of keys) {
    const plaintext = unpadPkcs7(
      aesCbcDecryptBytes(
        new Uint8Array(ciphertext),
        new Uint8Array(key),
        new Uint8Array(initializationVector),
      ),
    );
    const decoded = decodeUtf8Maybe(
      hashPrefix ? plaintext.subarray(32) : plaintext,
    );
    if (decoded !== null) {
      return decoded;
    }
  }
  logger.warning(
    "failed to decrypt cookie (AES-CBC) because UTF-8 decoding failed. Possibly the key is wrong?",
    { onlyOnce: true },
  );
  return null;
}

export function decryptAesGcm(
  ciphertext: Uint8Array,
  key: Uint8Array,
  nonce: Uint8Array,
  authenticationTag: Uint8Array,
  logger: CookieLogger,
  hashPrefix = false,
): string | null {
  try {
    const plaintext = aesGcmDecryptAndVerifyBytes(
      new Uint8Array(ciphertext),
      new Uint8Array(key),
      new Uint8Array(authenticationTag),
      new Uint8Array(nonce),
    );
    const decoded = decodeUtf8Maybe(
      hashPrefix ? plaintext.subarray(32) : plaintext,
    );
    if (decoded !== null) {
      return decoded;
    }
  } catch {
    logger.warning(
      "failed to decrypt cookie (AES-GCM) because the MAC check failed. Possibly the key is wrong?",
      { onlyOnce: true },
    );
    return null;
  }
  logger.warning(
    "failed to decrypt cookie (AES-GCM) because UTF-8 decoding failed. Possibly the key is wrong?",
    { onlyOnce: true },
  );
  return null;
}

export class DataParser {
  cursor = 0;
  constructor(
    readonly data: Uint8Array,
    readonly logger: CookieLogger,
  ) {}

  readBytes(numBytes: number): Uint8Array {
    if (numBytes < 0) {
      throw new ParserError(`invalid read of ${numBytes} bytes`);
    }
    const end = this.cursor + numBytes;
    if (end > this.data.length) {
      throw new ParserError("reached end of input");
    }
    const out = this.data.subarray(this.cursor, end);
    this.cursor = end;
    return out;
  }

  expectBytes(expectedValue: Uint8Array, message: string): void {
    const value = this.readBytes(expectedValue.length);
    if (!Buffer.from(value).equals(Buffer.from(expectedValue))) {
      throw new ParserError(
        `unexpected value: ${Buffer.from(value).toString("hex")} != ${Buffer.from(expectedValue).toString("hex")} (${message})`,
      );
    }
  }

  readUint(bigEndian = false): number {
    const data = Buffer.from(this.readBytes(4));
    return bigEndian ? data.readUInt32BE(0) : data.readUInt32LE(0);
  }

  readDouble(bigEndian = false): number {
    const data = Buffer.from(this.readBytes(8));
    return bigEndian ? data.readDoubleBE(0) : data.readDoubleLE(0);
  }

  readCString(): string {
    const chunks: number[] = [];
    while (true) {
      const char = this.readBytes(1)[0];
      if (char === undefined) {
        throw new ParserError("reached end of input");
      }
      if (char === 0) {
        return Buffer.from(chunks).toString();
      }
      chunks.push(char);
    }
  }

  skip(numBytes: number, description = "unknown"): void {
    if (numBytes > 0) {
      this.logger.debug(`skipping ${numBytes} bytes (${description})`);
      this.readBytes(numBytes);
    } else if (numBytes < 0) {
      throw new ParserError(`invalid skip of ${numBytes} bytes`);
    }
  }

  skipTo(offset: number, description = "unknown"): void {
    this.skip(offset - this.cursor, description);
  }

  skipToEnd(description = "unknown"): void {
    this.skipTo(this.data.length, description);
  }
}

export function parseSafariCookies(
  data: Uint8Array,
  jar = new YoutubeDLCookieJar(),
  logger: CookieLogger = new YDLLogger(),
): YoutubeDLCookieJar {
  const [pageSizes, bodyStart] = parseSafariCookiesHeader(data, logger);
  const parser = new DataParser(data.subarray(bodyStart), logger);
  for (const pageSize of pageSizes) {
    parseSafariCookiesPage(parser.readBytes(pageSize), jar, logger);
  }
  parser.skipToEnd("footer");
  return jar;
}

export class LenientSimpleCookie {
  readonly cookies = new Map<string, string>();
  readonly morsels = new Map<string, CookieMorsel>();

  constructor(data?: string) {
    if (data) {
      this.load(data);
    }
  }

  load(data: string): void {
    let morsel: CookieMorsel | null = null;
    for (const match of data.matchAll(COOKIE_PATTERN)) {
      if (match.groups?.bad) {
        morsel = null;
        continue;
      }

      const rawKey = match.groups?.key;
      const rawValue = match.groups?.val;
      if (!rawKey || !LEGAL_COOKIE_KEY_RE.test(rawKey)) {
        morsel = null;
        continue;
      }

      let key = rawKey;
      let isAttribute = false;
      if (key.startsWith("$")) {
        key = key.slice(1);
        isAttribute = true;
      }

      const lowerKey = key.toLocaleLowerCase();
      if (COOKIE_RESERVED_ATTRS.has(lowerKey)) {
        if (!morsel) {
          continue;
        }
        let attrValue: string | true;
        if (rawValue === undefined) {
          if (!COOKIE_FLAG_ATTRS.has(lowerKey)) {
            morsel = null;
            continue;
          }
          attrValue = true;
        } else {
          attrValue = decodeCookieValue(rawValue);
          if (hasCookieControlChar(attrValue)) {
            this.cookies.delete(morsel.key);
            this.morsels.delete(morsel.key);
            morsel = null;
            continue;
          }
        }
        morsel.setAttribute(lowerKey, attrValue);
      } else if (isAttribute) {
        morsel = null;
      } else if (rawValue !== undefined) {
        const realValue = decodeCookieValue(rawValue);
        if (hasCookieControlChar(realValue)) {
          morsel = null;
          continue;
        }
        morsel = this.morsels.get(key) ?? new CookieMorsel();
        morsel.set(key, realValue, rawValue);
        this.morsels.set(key, morsel);
        this.cookies.set(key, realValue);
      } else {
        morsel = null;
      }
    }
  }

  get(key: string): string | undefined {
    return this.cookies.get(key);
  }

  getMorsel(key: string): CookieMorsel | undefined {
    return this.morsels.get(key);
  }

  keys(): IterableIterator<string> {
    return this.morsels.keys();
  }

  values(): IterableIterator<CookieMorsel> {
    return this.morsels.values();
  }
}

export const COOKIE_MORSEL_ATTRIBUTE_KEYS = [
  "expires",
  "path",
  "comment",
  "domain",
  "max-age",
  "secure",
  "httponly",
  "version",
  "samesite",
] as const;

export class CookieMorsel implements Iterable<string> {
  key = "";
  value = "";
  codedValue = "";
  readonly attributes: Record<string, string | true | ""> = Object.fromEntries(
    COOKIE_MORSEL_ATTRIBUTE_KEYS.map((key) => [key, ""]),
  ) as Record<string, string | true | "">;

  [Symbol.iterator](): Iterator<string> {
    return COOKIE_MORSEL_ATTRIBUTE_KEYS[Symbol.iterator]();
  }

  set(key: string, value: string, codedValue = value): void {
    if (!LEGAL_COOKIE_KEY_RE.test(key)) {
      throw new Error(`Illegal key ${key}`);
    }
    this.key = key;
    this.value = value;
    this.codedValue = codedValue;
  }

  setAttribute(key: string, value: string | true): void {
    const lowerKey = key.toLocaleLowerCase();
    if (!COOKIE_RESERVED_ATTRS.has(lowerKey)) {
      throw new Error(`Invalid cookie attribute ${key}`);
    }
    this.attributes[lowerKey] = value;
  }

  update(values: Record<string, string | true>): void {
    for (const [key, value] of Object.entries(values)) {
      this.setAttribute(key, value);
    }
  }

  getAttribute(key: string): string | true | "" {
    return this.attributes[key.toLocaleLowerCase()] ?? "";
  }

  entries(): Array<[string, string | true | ""]> {
    return COOKIE_MORSEL_ATTRIBUTE_KEYS.map((key) => [key, this.attributes[key] ?? ""]);
  }

  values(): Array<string | true | ""> {
    return this.entries().map(([, value]) => value);
  }

  toTraversalRecord(): Record<string, string | true | ""> {
    return Object.fromEntries([
      ...this.entries(),
      ["key", this.key],
      ["value", this.value],
    ]);
  }
}

const COOKIE_RESERVED_ATTRS: Set<string> = new Set(COOKIE_MORSEL_ATTRIBUTE_KEYS);
const COOKIE_FLAG_ATTRS: Set<string> = new Set(["secure", "httponly"]);
const LEGAL_COOKIE_KEY_RE = /^[A-Za-z0-9_!#$%&'*+\-.:^`|~]+$/;
const COOKIE_PATTERN =
  /[ ]*(?<key>[^ =;]+)(?:[ ]*=[ ]*(?:(?<val>"(?:[^\\"]|\\.)*"|[A-Za-z]{3}, [A-Za-z0-9 -]{9,11} [0-9:]{8} GMT|[A-Za-z0-9_!#$%&'*+\-.:^`|~(),/<=>?@[\]{}]*)|(?<bad>(?:\\;|[^;])*?)))?[ ]*(?:[ ]+|;|$)/g;

function decodeCookieValue(value: string): string {
  if (value.length >= 2 && value.startsWith('"') && value.endsWith('"')) {
    return value.slice(1, -1).replace(/\\([0-3][0-7]{2}|.)/g, (_match, escaped: string) => {
      if (/^[0-3][0-7]{2}$/.test(escaped)) {
        return String.fromCharCode(Number.parseInt(escaped, 8));
      }
      return escaped;
    });
  }
  return value;
}

function hasCookieControlChar(value: string): boolean {
  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index);
    if (code <= 0x1f || code === 0x7f) {
      return true;
    }
  }
  return false;
}

function parseNetscapeCookieLine(line: string): Cookie {
  let httpOnly = false;
  if (line.startsWith(YoutubeDLCookieJar.HTTPONLY_PREFIX)) {
    httpOnly = true;
    line = line.slice(YoutubeDLCookieJar.HTTPONLY_PREFIX.length);
  }
  const parts = line.split("\t");
  if (parts.length !== YoutubeDLCookieJar.ENTRY_LEN) {
    throw new Error(`invalid length ${parts.length}`);
  }
  const [domain, , path, secure, expires, name, value] = parts as [
    string,
    string,
    string,
    string,
    string,
    string,
    string,
  ];
  if (expires && !/^[0-9]+(?:\.[0-9]+)?$/.test(expires)) {
    throw new Error(`invalid expires at ${expires}`);
  }
  return new Cookie({
    domain,
    path,
    secure: secure.toUpperCase() === "TRUE",
    expires: expires ? Number(expires) || null : null,
    name,
    value,
    httpOnly,
    discard: !expires || expires === "0",
  });
}

function cookieMatchesUrl(cookie: Cookie, url: URL, now: number): boolean {
  if (cookie.isExpired(now)) {
    return false;
  }
  if (cookie.secure && url.protocol !== "https:") {
    return false;
  }
  const host = url.hostname.toLowerCase();
  const domain = cookie.domain.replace(/^\./, "").toLowerCase();
  if (host !== domain && !host.endsWith(`.${domain}`)) {
    return false;
  }
  return url.pathname.startsWith(cookie.path || "/");
}

function filterCookieJarForUrl(
  source: YoutubeDLCookieJar,
  url: string,
): YoutubeDLCookieJar {
  const jar = new YoutubeDLCookieJar();
  for (const cookie of source.getCookiesForUrl(url)) {
    jar.setCookie(cookie);
  }
  return jar;
}

function sweetCookieOptions(
  browserName: string,
  profile: string | null,
  url: string,
): GetCookiesOptions | null {
  const options: GetCookiesOptions = {
    url,
    mode: "merge",
    includeExpired: false,
    timeoutMs: 5000,
  };
  if (browserName === "firefox") {
    options.browsers = ["firefox"];
    if (profile) {
      options.firefoxProfile = profile;
    }
    return options;
  }
  if (browserName === "safari") {
    options.browsers = ["safari"];
    if (profile) {
      options.safariCookiesFile = profile;
    }
    return options;
  }
  if (browserName === "edge") {
    options.browsers = ["edge"];
    if (profile) {
      options.edgeProfile = profile;
    }
    return options;
  }
  const chromiumBrowser = sweetChromiumBrowser(browserName);
  if (chromiumBrowser) {
    options.browsers = ["chrome"];
    if (profile) {
      options.chromeProfile = profile;
    }
    if (process.platform === "darwin") {
      options.chromiumBrowser = chromiumBrowser;
    }
    return options;
  }
  return null;
}

function sweetChromiumBrowser(
  browserName: string,
): GetCookiesOptions["chromiumBrowser"] | null {
  if (browserName === "chrome") {
    return "chrome";
  }
  if (browserName === "brave") {
    return "brave";
  }
  if (browserName === "chromium") {
    return "chromium";
  }
  return null;
}

