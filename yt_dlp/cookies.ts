async function newest(files: readonly string[]): Promise<string | null> {
  let result: string | null = null;
  let resultMtime = -Infinity;
  for (const file of files) {
    try {
      const info = await stat(file);
      if (info.mtimeMs > resultMtime) {
        result = file;
        resultMtime = info.mtimeMs;
      }
    } catch {}
  }
  return result;
}

async function findFiles(root: string, filename: string): Promise<string[]> {
  const result: string[] = [];
  async function walk(dir: string): Promise<void> {
    let entries: string[];
    try {
      entries = await readdir(dir);
    } catch {
      return;
    }
    await Promise.all(
      entries.map(async (entry) => {
        const full = join(dir, entry);
        const info = await stat(full).catch(() => null);
        if (!info) {
          return;
        }
        if (info.isDirectory()) {
          await walk(full);
        } else if (basename(full) === filename) {
          result.push(full);
        }
      }),
    );
  }
  await walk(root);
  return result;
}

function mergeCookieJars(
  jars: readonly YoutubeDLCookieJar[],
): YoutubeDLCookieJar {
  const output = new YoutubeDLCookieJar();
  for (const jar of jars) {
    for (const cookie of jar) {
      output.setCookie(cookie);
    }
    if (jar.filename) {
      output.filename = jar.filename;
    }
  }
  return output;
}

function parseBrowserSpecification(
  browserName: string,
  profile?: string | null,
  keyring?: string | null,
  container?: string | null,
): [string, string | null, string | null, string | null] {
  if (!SUPPORTED_BROWSERS.has(browserName)) {
    throw new Error(`unsupported browser: "${browserName}"`);
  }
  if (keyring && !SUPPORTED_KEYRINGS.includes(keyring)) {
    throw new Error(`unsupported keyring: "${keyring}"`);
  }
  const expandedProfile =
    profile && isPath(expandPath(profile))
      ? expandPath(profile)
      : (profile ?? null);
  return [browserName, expandedProfile, keyring ?? null, container ?? null];
}

function isPath(value: string): boolean {
  return value.includes("/") || value.includes("\\");
}

function configHome(): string {
  return process.env.XDG_CONFIG_HOME ?? expandPath("~/.config");
}

function expandPath(path: string): string {
  if (path === "~") {
    return process.env.HOME ?? path;
  }
  if (path.startsWith("~/")) {
    return join(process.env.HOME ?? "~", path.slice(2));
  }
  return expandEnv(path);
}

function expandEnv(path: string): string {
  return path.replaceAll(
    /%([^%]+)%/g,
    (_, key: string) => process.env[key] ?? `%${key}%`,
  );
}

async function fileExists(path: string | null): Promise<boolean> {
  if (!path) {
    return false;
  }
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

function trueOrFalse(value: boolean): "TRUE" | "FALSE" {
  return value ? "TRUE" : "FALSE";
}

function bufferishToString(value: string | Uint8Array | null): string {
  if (typeof value === "string") {
    return value;
  }
  if (!value) {
    return "";
  }
  return Buffer.from(value).toString();
}

