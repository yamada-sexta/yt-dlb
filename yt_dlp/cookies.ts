type ChromeCookieRow = {
  host_key: string | Uint8Array;
  name: string | Uint8Array;
  value: string | Uint8Array;
  encrypted_value: Uint8Array | null;
  path: string | Uint8Array;
  expires_utc: number | null;
  is_secure: number;
};

function processChromeCookie(
  decryptor: ChromeCookieDecryptor,
  row: ChromeCookieRow,
): [boolean, Cookie | null] {
  const hostKey = bufferishToString(row.host_key);
  const name = bufferishToString(row.name);
  let value = bufferishToString(row.value);
  const path = bufferishToString(row.path);
  const encryptedValue = row.encrypted_value;
  const encrypted =
    !value && encryptedValue !== null && encryptedValue.length > 0;
  if (encrypted) {
    value = decryptor.decrypt(encryptedValue) ?? "";
    if (!value) {
      return [true, null];
    }
  }
  return [
    Boolean(encrypted),
    new Cookie({
      name,
      value,
      domain: hostKey,
      path,
      secure: Boolean(row.is_secure),
      expires: row.expires_utc || null,
      discard: false,
    }),
  ];
}

function parseSafariCookiesHeader(
  data: Uint8Array,
  logger: CookieLogger,
): [number[], number] {
  const parser = new DataParser(data, logger);
  parser.expectBytes(Buffer.from("cook"), "database signature");
  const pages = parser.readUint(true);
  return [
    Array.from({ length: pages }, () => parser.readUint(true)),
    parser.cursor,
  ];
}

function parseSafariCookiesPage(
  data: Uint8Array,
  jar: YoutubeDLCookieJar,
  logger: CookieLogger,
): void {
  const parser = new DataParser(data, logger);
  parser.expectBytes(Buffer.from([0, 0, 1, 0]), "page signature");
  const cookieCount = parser.readUint();
  const offsets = Array.from({ length: cookieCount }, () => parser.readUint());
  if (!cookieCount) {
    logger.debug(`a cookies page of size ${data.length} has no cookies`);
    return;
  }
  const firstOffset = offsets[0];
  if (firstOffset === undefined) {
    throw new Error("Safari cookies page has no first cookie offset");
  }
  parser.skipTo(firstOffset, "unknown page header field");
  for (const offset of offsets) {
    parser.skipTo(offset, "space between records");
    const recordLength = parseSafariCookiesRecord(
      data.subarray(offset),
      jar,
      logger,
    );
    parser.readBytes(recordLength);
  }
  parser.skipToEnd("space in between pages");
}

function parseSafariCookiesRecord(
  data: Uint8Array,
  jar: YoutubeDLCookieJar,
  logger: CookieLogger,
): number {
  const parser = new DataParser(data, logger);
  const recordSize = parser.readUint();
  parser.skip(4, "unknown record field 1");
  const flags = parser.readUint();
  const secure = Boolean(flags & 0x0001);
  parser.skip(4, "unknown record field 2");
  const domainOffset = parser.readUint();
  const nameOffset = parser.readUint();
  const pathOffset = parser.readUint();
  const valueOffset = parser.readUint();
  parser.skip(8, "unknown record field 3");
  const firstStringOffset = safariStringOffset(
    Math.min(domainOffset, nameOffset, pathOffset, valueOffset),
  );
  const dateParser = new DataParser(
    data.subarray(Math.max(0, firstStringOffset - 16)),
    logger,
  );
  const expirationDate = macAbsoluteTimeToPosix(dateParser.readDouble());
  dateParser.readDouble();

  try {
    const domain = readSafariCString(data, domainOffset, logger);
    const name = readSafariCString(data, nameOffset, logger);
    const path = readSafariCString(data, pathOffset, logger);
    const value = readSafariCString(data, valueOffset, logger);
    parser.skipTo(recordSize, "space at the end of the record");
    jar.setCookie(
      new Cookie({
        name,
        value,
        domain,
        path,
        secure,
        expires: expirationDate,
        discard: false,
      }),
    );
  } catch {
    logger.warning(
      "failed to parse Safari cookie because UTF-8 decoding failed",
      { onlyOnce: true },
    );
  }
  return recordSize;
}

function safariStringOffset(offset: number): number {
  return Math.max(0, offset - 1);
}

function readSafariCString(
  data: Uint8Array,
  offset: number,
  logger: CookieLogger,
): string {
  return new DataParser(
    data.subarray(safariStringOffset(offset)),
    logger,
  ).readCString();
}

function macAbsoluteTimeToPosix(timestamp: number): number {
  return Math.trunc(Date.UTC(2001, 0, 1) / 1000 + timestamp);
}

export function getLinuxDesktopEnvironment(
  env: Record<string, string | number | undefined>,
  logger: CookieLogger = new YDLLogger(),
): LinuxDesktopEnvironment {
  const xdgCurrentDesktop = env.XDG_CURRENT_DESKTOP;
  const desktopSession = String(env.DESKTOP_SESSION ?? "");
  if (xdgCurrentDesktop !== undefined) {
    for (const part of String(xdgCurrentDesktop)
      .split(":")
      .map((item) => item.trim())) {
      if (part === "Unity") {
        return desktopSession.includes("gnome-fallback")
          ? LinuxDesktopEnvironment.GNOME
          : LinuxDesktopEnvironment.UNITY;
      }
      if (part === "Deepin") {
        return LinuxDesktopEnvironment.DEEPIN;
      }
      if (part === "GNOME") {
        return LinuxDesktopEnvironment.GNOME;
      }
      if (part === "X-Cinnamon") {
        return LinuxDesktopEnvironment.CINNAMON;
      }
      if (part === "KDE") {
        const kdeVersion = env.KDE_SESSION_VERSION;
        if (kdeVersion === "5") {
          return LinuxDesktopEnvironment.KDE5;
        }
        if (kdeVersion === "6") {
          return LinuxDesktopEnvironment.KDE6;
        }
        if (kdeVersion === "4") {
          return LinuxDesktopEnvironment.KDE4;
        }
        logger.info(`unknown KDE version: "${kdeVersion}". Assuming KDE4`);
        return LinuxDesktopEnvironment.KDE4;
      }
      if (part === "Pantheon") {
        return LinuxDesktopEnvironment.PANTHEON;
      }
      if (part === "XFCE") {
        return LinuxDesktopEnvironment.XFCE;
      }
      if (part === "UKUI") {
        return LinuxDesktopEnvironment.UKUI;
      }
      if (part === "LXQt") {
        return LinuxDesktopEnvironment.LXQT;
      }
    }
    logger.debug(
      `XDG_CURRENT_DESKTOP is set to an unknown value: "${xdgCurrentDesktop}"`,
    );
  }

  if (desktopSession === "deepin") {
    return LinuxDesktopEnvironment.DEEPIN;
  }
  if (desktopSession === "mate" || desktopSession === "gnome") {
    return LinuxDesktopEnvironment.GNOME;
  }
  if (desktopSession === "kde4" || desktopSession === "kde-plasma") {
    return LinuxDesktopEnvironment.KDE4;
  }
  if (desktopSession === "kde") {
    return "KDE_SESSION_VERSION" in env
      ? LinuxDesktopEnvironment.KDE4
      : LinuxDesktopEnvironment.KDE3;
  }
  if (desktopSession.includes("xfce") || desktopSession === "xubuntu") {
    return LinuxDesktopEnvironment.XFCE;
  }
  if (desktopSession === "ukui") {
    return LinuxDesktopEnvironment.UKUI;
  }
  logger.debug(
    `DESKTOP_SESSION is set to an unknown value: "${desktopSession}"`,
  );

  if ("GNOME_DESKTOP_SESSION_ID" in env) {
    return LinuxDesktopEnvironment.GNOME;
  }
  if ("KDE_FULL_SESSION" in env) {
    return "KDE_SESSION_VERSION" in env
      ? LinuxDesktopEnvironment.KDE4
      : LinuxDesktopEnvironment.KDE3;
  }
  return LinuxDesktopEnvironment.OTHER;
}

